// Generates src/fixtures.generated.ts from ../../fixtures so the demo mode can
// replay frames without a raw-file loader. Provenance is kept in the labels.
// Run: npm run gen:fixtures   (tests/mobile-fixtures-drift.test.ts fails if this file drifts)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../fixtures/jk-b2a16s");
const files = {
  deviceInfo: "device-info/hw3-sw3.3.0.upstream.hex",
  settings: "settings/default.upstream.hex",
  balanced: "status/16s-balanced.upstream.hex",
  unbalanced: "status/16s-unbalanced.synthetic.hex",
};
const lines = [
  "// GENERATED by scripts/gen-fixtures.mjs - do not edit.",
  "// Sources: fixtures/jk-b2a16s (see its README for provenance).",
  "// `unbalanced` is SYNTHETIC and must never be shown as a device measurement.",
  "export const FIXTURE_HEX = {",
];
for (const [key, file] of Object.entries(files)) {
  const hex = readFileSync(resolve(root, file), "utf8").trim().split(/\s+/).join(" ");
  lines.push(`  /** ${file} */`, `  ${key}: "${hex}",`);
}
lines.push("} as const;", "");
writeFileSync(resolve(here, "../src/fixtures.generated.ts"), lines.join("\n"));
